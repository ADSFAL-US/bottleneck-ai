# tools/example/tool.py
# Пример простого инструмента, показывающего, как создавать свои тулы в системе.
# Этот инструмент складывает два числа и возвращает результат.

from tool_router import BaseTool  # базовый класс для всех инструментов

class Tool(BaseTool):
    """
    Каждый инструмент должен предоставлять:
    1) get_manifest() -> dict с описанием и параметрами
    2) run(**kwargs) -> dict с результатом или ошибкой
    """

    def get_manifest(self):
        """
        Возвращает манифест – мета-информацию, которую агент использует для вызова инструмента.
        Содержит:
        - description: понятное описание того, что делает инструмент.
        - parameters: схема входных параметров (тип, описание, обязательность и т.д.).
        """
        return {
            "description": (
                "Складывает два целых или вещественных числа. "
                "Полезен для демонстрации базовой структуры инструмента: "
                "приём параметров, валидация, возврат результата."
            ),
            "parameters": {
                # Параметр "a" – обязательный
                "a": {
                    "type": "number",          # может быть int или float
                    "description": "Первое слагаемое"
                },
                # Параметр "b" – обязательный
                "b": {
                    "type": "number",
                    "description": "Второе слагаемое"
                },
                # Необязательный параметр "round_digits" – округление результата
                "round_digits": {
                    "type": "integer",
                    "description": "Округлить результат до указанного количества знаков после запятой (опционально)"
                }
            }
        }

    def run(self, **kwargs):
        """
        Основной метод выполнения инструмента.
        Получает аргументы как именованные параметры (через **kwargs).
        Должен возвращать словарь, который будет передан AI.
        Рекомендуется всегда включать ключи: 'success' (bool) и либо 'result', либо 'error'.
        """
        # 1. Извлекаем параметры с безопасными значениями по умолчанию
        a = kwargs.get("a")      # если параметр не передан, get вернёт None
        b = kwargs.get("b")
        round_digits = kwargs.get("round_digits")

        # 2. Валидация обязательных параметров
        if a is None:
            return {"error": "Отсутствует обязательный параметр 'a'"}
        if b is None:
            return {"error": "Отсутствует обязательный параметр 'b'"}

        # 3. Проверка типов (числа)
        if not isinstance(a, (int, float)):
            return {"error": f"Параметр 'a' должен быть числом, получен {type(a).__name__}"}
        if not isinstance(b, (int, float)):
            return {"error": f"Параметр 'b' должен быть числом, получен {type(b).__name__}"}

        # 4. Проверка необязательного параметра round_digits (если задан)
        if round_digits is not None:
            if not isinstance(round_digits, int):
                return {"error": "Параметр 'round_digits' должен быть целым числом"}
            if round_digits < 0:
                return {"error": "round_digits не может быть отрицательным"}

        # 5. Выполнение основной логики
        result = a + b

        # 6. Применяем округление, если запрошено
        if round_digits is not None:
            result = round(result, round_digits)

        # 7. Успешный возврат результата
        return {
            "success": True,
            "result": result,
            "message": f"Сумма {a} и {b} равна {result}"
        }